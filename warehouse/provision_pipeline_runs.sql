-- Run manually as BLOCKCHAIN_ADMIN_ROLE. Runtime code must not execute this
-- DDL or receive CREATE, DELETE, TRUNCATE, or OWNERSHIP privileges.
USE ROLE BLOCKCHAIN_ADMIN_ROLE;

CREATE TABLE IF NOT EXISTS BLOCKCHAIN_ANALYTICS.CONTROL.PIPELINE_RUNS (
  PIPELINE_NAME VARCHAR NOT NULL,
  RUN_ID VARCHAR NOT NULL,
  RUN_TYPE VARCHAR NOT NULL,
  STARTED_AT TIMESTAMP_TZ NOT NULL,
  FINISHED_AT TIMESTAMP_TZ,
  STATUS VARCHAR NOT NULL,
  SOURCE_START_POSITION NUMBER(38, 0),
  SOURCE_END_POSITION NUMBER(38, 0),
  SOURCE_HEAD_POSITION NUMBER(38, 0),
  SAFE_HEAD_POSITION NUMBER(38, 0),
  WATERMARK_BEFORE NUMBER(38, 0),
  WATERMARK_AFTER NUMBER(38, 0),
  MADE_PROGRESS BOOLEAN,
  RECORDS_READ NUMBER(38, 0) NOT NULL DEFAULT 0,
  RECORDS_WRITTEN NUMBER(38, 0) NOT NULL DEFAULT 0,
  RECORDS_INSERTED NUMBER(38, 0) NOT NULL DEFAULT 0,
  RECORDS_UPDATED NUMBER(38, 0) NOT NULL DEFAULT 0,
  RECORDS_QUARANTINED NUMBER(38, 0) NOT NULL DEFAULT 0,
  RETRY_COUNT NUMBER(38, 0) NOT NULL DEFAULT 0,
  DURATION_SECONDS NUMBER(18, 3),
  ERROR_STAGE VARCHAR,
  ERROR_CLASS VARCHAR,
  METRIC_DETAILS VARIANT NOT NULL,
  CONSTRAINT PK_PIPELINE_RUNS PRIMARY KEY (PIPELINE_NAME, RUN_ID)
)
COMMENT = 'Provider-neutral pipeline run lifecycle and aggregate metrics';

GRANT USAGE ON DATABASE BLOCKCHAIN_ANALYTICS
  TO ROLE BLOCKCHAIN_PIPELINE_ROLE;
GRANT USAGE ON SCHEMA BLOCKCHAIN_ANALYTICS.CONTROL
  TO ROLE BLOCKCHAIN_PIPELINE_ROLE;
GRANT SELECT, INSERT, UPDATE
  ON TABLE BLOCKCHAIN_ANALYTICS.CONTROL.PIPELINE_RUNS
  TO ROLE BLOCKCHAIN_PIPELINE_ROLE;
