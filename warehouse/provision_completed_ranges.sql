USE ROLE BLOCKCHAIN_ADMIN_ROLE;

CREATE TABLE IF NOT EXISTS
  BLOCKCHAIN_ANALYTICS.CONTROL.PIPELINE_COMPLETED_RANGES (
    PIPELINE_NAME VARCHAR NOT NULL,
    SOURCE_NAME VARCHAR NOT NULL,
    CHAIN_ID NUMBER(38, 0) NOT NULL,
    WATERMARK_TYPE VARCHAR NOT NULL,
    START_BLOCK NUMBER(38, 0) NOT NULL,
    END_BLOCK NUMBER(38, 0) NOT NULL,
    SUCCESSFUL_RUN_ID VARCHAR NOT NULL,
    COMPLETED_AT TIMESTAMP_TZ NOT NULL,
    CONSTRAINT CK_PIPELINE_COMPLETED_RANGE_ORDER
      CHECK (END_BLOCK >= START_BLOCK)
  )
COMMENT = 'Append-only successful source ranges used to prove coverage';

GRANT SELECT, INSERT
  ON TABLE BLOCKCHAIN_ANALYTICS.CONTROL.PIPELINE_COMPLETED_RANGES
  TO ROLE BLOCKCHAIN_PIPELINE_ROLE;
