-- Run manually as the project infrastructure owner. Runtime code must not
-- execute this DDL or use BLOCKCHAIN_ADMIN_ROLE.
USE ROLE BLOCKCHAIN_ADMIN_ROLE;

CREATE SCHEMA IF NOT EXISTS BLOCKCHAIN_ANALYTICS.CONTROL
  COMMENT = 'Operational control state separate from analytical models';

CREATE TABLE IF NOT EXISTS BLOCKCHAIN_ANALYTICS.CONTROL.PIPELINE_WATERMARKS (
  PIPELINE_NAME VARCHAR NOT NULL,
  SOURCE_NAME VARCHAR NOT NULL,
  CHAIN_ID NUMBER(38, 0) NOT NULL,
  WATERMARK_TYPE VARCHAR NOT NULL,
  COMMITTED_VALUE NUMBER(38, 0) NOT NULL,
  SUCCESSFUL_RUN_ID VARCHAR NOT NULL,
  UPDATED_AT TIMESTAMP_TZ NOT NULL,
  CONSTRAINT PK_PIPELINE_WATERMARKS PRIMARY KEY (
    PIPELINE_NAME,
    SOURCE_NAME,
    CHAIN_ID,
    WATERMARK_TYPE
  )
)
COMMENT = 'Current committed source position for independent forward pipelines';

GRANT USAGE ON DATABASE BLOCKCHAIN_ANALYTICS
  TO ROLE BLOCKCHAIN_PIPELINE_ROLE;
GRANT USAGE ON SCHEMA BLOCKCHAIN_ANALYTICS.CONTROL
  TO ROLE BLOCKCHAIN_PIPELINE_ROLE;
GRANT SELECT, INSERT, UPDATE
  ON TABLE BLOCKCHAIN_ANALYTICS.CONTROL.PIPELINE_WATERMARKS
  TO ROLE BLOCKCHAIN_PIPELINE_ROLE;
